async function writeIfChanged(filePath, content) {
  const existing = await fs.readFile(filePath, 'utf8').catch(() => '');
  if (existing === content) return false;
  await fs.writeFile(filePath, content, 'utf8');
  return true;
}

export async function generateXboardVersionManifest() {
  const versions = await discoverVersions();
  if (!versions.length) {
    throw new Error(`No XBoard version files found in ${versionDir}`);
  }

  const nextPayload = {
    latest: versions[0],
    versions
  };
  const existingSource = await fs.readFile(manifestPath, 'utf8').catch(() => '');
  const existingManifest = existingSource ? parseExistingManifest(existingSource) : null;
  const manifest = existingManifest && sameVersionPayload(existingManifest, nextPayload) ? {
    generatedAt: existingManifest.generatedAt,
    ...nextPayload
  } : {
    generatedAt: new Date().toISOString(),
    ...nextPayload
  };

  const manifestChanged = await writeIfChanged(manifestPath, serializeManifest(manifest));
  const indexChanged = await writeIfChanged(indexPath, serializeIndex(manifest));

  return { manifest, manifestChanged, indexChanged };
}

async function runCli() {
  try {
    const result = await generateXboardVersionManifest();
    console.log('[xboard-version-manifest]', {
      latest: result.manifest.latest.file,
      versions: result.manifest.versions.length,
      manifestChanged: result.manifestChanged,
      indexChanged: result.indexChanged
    });
  } catch (error) {
    console.error('[xboard-version-manifest] failed');
    console.error(error);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  runCli();
}
